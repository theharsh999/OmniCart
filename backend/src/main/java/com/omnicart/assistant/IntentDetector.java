package com.omnicart.assistant;

import java.util.Locale;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Rule-based Intent and Entity Detector for OmniCart Assistant.
 * Uses normalized text matching, keyword stems, and regex patterns.
 */
public class IntentDetector {

    public record DetectionResult(
            ChatIntent intent,
            String targetEntity,
            String normalizedQuery
    ) {}

    private static final Pattern SQL_INJECTION_PATTERN = Pattern.compile(
            "\\b(drop\\s+table|delete\\s+from|update\\s+\\w+\\s+set|insert\\s+into|alter\\s+table|truncate\\s+table|union\\s+select|exec\\s*\\()",
            Pattern.CASE_INSENSITIVE
    );

    public DetectionResult detect(String rawMessage) {
        if (rawMessage == null || rawMessage.trim().isEmpty()) {
            return new DetectionResult(ChatIntent.UNKNOWN, "", "");
        }

        String message = normalize(rawMessage);

        // 1. Safety & SQL check
        if (SQL_INJECTION_PATTERN.matcher(message).find()) {
            return new DetectionResult(ChatIntent.SECURITY_VIOLATION, "", message);
        }

        // 2. Greetings
        if (matchesAny(message, "^(hi|hello|hey|good morning|good evening|good afternoon|namaste|greetings)($|\\b)")) {
            return new DetectionResult(ChatIntent.GREETING, "", message);
        }

        // 3. General Help
        if (matchesAny(message,
                "what can you do", "help me use omnicart", "what can you help me with",
                "^help$", "how do you work", "what are your capabilities", "show help", "commands")) {
            return new DetectionResult(ChatIntent.HELP, "", message);
        }

        // 4. Instructions / How-To
        if (matchesAny(message, "how do i create a bill", "how to create a bill", "how to bill", "how do i bill", "how to make a bill", "create a bill instructions")) {
            return new DetectionResult(ChatIntent.BILLING_HELP, "", message);
        }
        if (matchesAny(message, "how do i check product availability", "how to check product availability", "how to check stock", "check availability")) {
            return new DetectionResult(ChatIntent.INVENTORY_HELP, "", message);
        }

        // 5. Shop Status & Summary
        if (matchesAny(message,
                "summary of my shop", "summary of the shop", "shop's current status", "shop current status",
                "shop status", "store status", "store overview", "shop overview", "give me a summary",
                "how is my shop doing", "overall summary", "business summary")) {
            return new DetectionResult(ChatIntent.SHOP_SUMMARY, "", message);
        }

        // 6. Category Statistics
        if (matchesAny(message, "which category has the most products", "category with the most products", "category with most products", "top category", "highest category", "category with highest products")) {
            return new DetectionResult(ChatIntent.CATEGORY_STATS, "", message);
        }

        // 7. Cashier Leaderboard & Breakdown
        if (matchesAny(message, "which cashier generated the most bills", "cashier generated the most bills", "cashier with most bills", "top cashier", "best cashier", "cashier ranking", "highest bills cashier")) {
            return new DetectionResult(ChatIntent.CASHIER_LEADERBOARD, "", message);
        }
        if (matchesAny(message, "cashier-wise sales for today", "cashier wise sales for today", "cashier-wise sales", "cashier wise sales", "cashier sales today", "cashier breakdown", "sales by cashier today")) {
            return new DetectionResult(ChatIntent.CASHIER_TODAY_BREAKDOWN, "", message);
        }

        // 8. Self-referential cashier questions (for Cashiers)
        if (matchesAny(message, "how many bills have i generated today", "how many bills did i generate today", "my bills today", "bills generated by me today", "how many bills did i do today")) {
            return new DetectionResult(ChatIntent.MY_BILLS_TODAY, "", message);
        }
        if (matchesAny(message, "how many bills did i generate this month", "my bills this month", "my sales this month", "bills i made this month")) {
            return new DetectionResult(ChatIntent.MY_MONTHLY_BILLS, "", message);
        }
        if (matchesAny(message, "what are my sales today", "my sales today", "my revenue today", "how much did i sell today", "my today's sales")) {
            return new DetectionResult(ChatIntent.MY_SALES_TODAY, "", message);
        }
        if (matchesAny(message, "show my recent bills", "my recent bills", "my recent sales", "my latest bills", "show my bills")) {
            return new DetectionResult(ChatIntent.MY_RECENT_BILLS, "", message);
        }

        // 9. Named Cashier queries (e.g., "How many bills did Omkar generate?", "Show Ansh's sales")
        String cashierName = extractCashierName(message);
        if (cashierName != null) {
            if (message.contains("bill") || message.contains("invoice")) {
                return new DetectionResult(ChatIntent.CASHIER_BILLS, cashierName, message);
            }
            if (message.contains("sale") || message.contains("revenue") || message.contains("sold") || message.contains("amount")) {
                return new DetectionResult(ChatIntent.CASHIER_SALES, cashierName, message);
            }
            // default for cashier query
            return new DetectionResult(ChatIntent.CASHIER_SALES, cashierName, message);
        }

        // 10. Store-wide Sales & Bills
        if (matchesAny(message, "what are today's total sales", "today's total sales", "total sales today", "today's sales", "sales today", "today total sales", "how much did we sell today", "today revenue")) {
            return new DetectionResult(ChatIntent.TODAY_SALES, "", message);
        }
        if (matchesAny(message, "how many bills were generated today", "bills were generated today", "bills generated today", "bills today", "today's bills", "today bills", "invoices today", "how many invoices today")) {
            return new DetectionResult(ChatIntent.TODAY_BILLS, "", message);
        }
        if (matchesAny(message, "what were yesterday's sales", "what were yesterday sales", "yesterday's sales", "yesterday sales", "sales yesterday", "yesterday revenue", "bills yesterday")) {
            return new DetectionResult(ChatIntent.YESTERDAY_SALES, "", message);
        }
        if (matchesAny(message, "show total sales this month", "total sales this month", "sales this month", "monthly sales", "sales for this month", "revenue this month", "this month sales")) {
            return new DetectionResult(ChatIntent.MONTHLY_SALES, "", message);
        }
        if (matchesAny(message, "show recent sales", "recent sales", "recent bills", "latest sales", "latest bills", "show recent", "last few sales", "last few bills")) {
            return new DetectionResult(ChatIntent.RECENT_SALES, "", message);
        }

        // 11. Inventory & Products
        if (matchesAny(message, "how many products are available", "total products", "how many items", "product count", "total products available", "total items in store")) {
            return new DetectionResult(ChatIntent.TOTAL_PRODUCTS, "", message);
        }
        if (matchesAny(message, "which products are low in stock", "products are low in stock", "low in stock", "low stock products", "low stock", "items running low", "low inventory")) {
            return new DetectionResult(ChatIntent.LOW_STOCK, "", message);
        }
        if (matchesAny(message, "which products are out of stock", "products are out of stock", "out of stock", "zero stock", "no stock", "sold out")) {
            return new DetectionResult(ChatIntent.OUT_OF_STOCK, "", message);
        }

        // 12. Product Price queries
        if (isPriceQuery(message)) {
            String product = extractProductQuery(message, "price");
            return new DetectionResult(ChatIntent.PRODUCT_PRICE, product, message);
        }

        // 13. Product Stock queries
        if (isStockQuery(message)) {
            String product = extractProductQuery(message, "stock");
            return new DetectionResult(ChatIntent.PRODUCT_STOCK, product, message);
        }

        // 14. Product Search queries
        if (isSearchQuery(message)) {
            String product = extractProductQuery(message, "search");
            return new DetectionResult(ChatIntent.PRODUCT_SEARCH, product, message);
        }

        return new DetectionResult(ChatIntent.UNKNOWN, "", message);
    }

    private static String normalize(String input) {
        String s = input.trim().toLowerCase(Locale.ROOT);
        // Replace punctuation except hyphens inside SKUs
        s = s.replaceAll("[?,!.;]+$", "");
        s = s.replaceAll("\\s+", " ");
        return s.trim();
    }

    private static boolean matchesAny(String input, String... candidates) {
        for (String c : candidates) {
            if (c.startsWith("^") || c.endsWith("$") || c.contains("\\b")) {
                if (Pattern.compile(c, Pattern.CASE_INSENSITIVE).matcher(input).find()) {
                    return true;
                }
            } else if (input.contains(c)) {
                return true;
            }
        }
        return false;
    }

    private static String extractCashierName(String message) {
        // Look for common cashiers or patterns like "did <name> generate", "show <name>'s sales"
        Matcher m1 = Pattern.compile("\\b(?:did|by|for)\\s+([a-zA-Z]{3,20})(?:'s)?\\s+(?:generate|sell|make|have)\\b").matcher(message);
        if (m1.find()) {
            return cleanEntity(m1.group(1));
        }

        Matcher m2 = Pattern.compile("\\bshow\\s+([a-zA-Z]{3,20})'s\\s+(?:sales|bills|performance)\\b").matcher(message);
        if (m2.find()) {
            return cleanEntity(m2.group(1));
        }

        Matcher m3 = Pattern.compile("\\b([a-zA-Z]{3,20})'s\\s+(?:sales|bills)\\b").matcher(message);
        if (m3.find()) {
            String candidate = m3.group(1);
            if (!candidate.equalsIgnoreCase("today") && !candidate.equalsIgnoreCase("yesterday") && !candidate.equalsIgnoreCase("shop")) {
                return cleanEntity(candidate);
            }
        }

        // Check if message explicitly mentions known demo names
        if (message.contains("omkar")) return "Omkar";
        if (message.contains("ansh")) return "Ansh";

        return null;
    }

    private static boolean isPriceQuery(String msg) {
        return msg.contains("price of") || msg.contains("what is the price") || msg.contains("cost of")
                || msg.contains("how much is") || msg.contains("selling price of")
                || (msg.contains("price") && !msg.contains("stock") && !msg.contains("sales"));
    }

    private static boolean isStockQuery(String msg) {
        return msg.contains("stock of") || msg.contains("current stock") || msg.contains("how much stock")
                || msg.contains("how many") && (msg.contains("left") || msg.contains("in stock"))
                || msg.contains("is in stock") || msg.contains("available stock")
                || (msg.contains("stock") && !msg.contains("low stock") && !msg.contains("out of stock"));
    }

    private static boolean isSearchQuery(String msg) {
        return msg.startsWith("search for") || msg.startsWith("search") || msg.startsWith("find")
                || msg.contains("do you have") || msg.contains("search for a product");
    }

    private static String extractProductQuery(String msg, String context) {
        String clean = msg;
        // Strip common question prefixes
        clean = clean.replaceAll("^(what is the (price|current stock|stock) of (a|an|the|particular)?|price of (a|an|the)?|stock of (a|an|the)?|how much is (a|an|the)?|cost of (a|an|the)?|how much stock of (a|an|the)?|how many|is|in stock|search for (a|an|the)?|search (a|an|the)?|find (a|an|the)?|do you have (a|an|the)?)\\s*", "");
        clean = clean.replaceAll("\\s*(left|in stock|available|units|price|cost|stock)\\s*$", "");
        clean = clean.replaceAll("[?,!]+$", "").trim();

        if (clean.equalsIgnoreCase("a particular product") || clean.equalsIgnoreCase("particular product") || clean.equalsIgnoreCase("product")) {
            return "";
        }
        return cleanEntity(clean);
    }

    private static String cleanEntity(String entity) {
        if (entity == null || entity.isBlank()) return "";
        String s = entity.replaceAll("[^a-zA-Z0-9\\s()\\-]", "").trim();
        if (s.isEmpty()) return "";
        return Character.toUpperCase(s.charAt(0)) + s.substring(1);
    }
}
